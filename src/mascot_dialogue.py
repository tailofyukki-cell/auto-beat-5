def mascot_result_line(mascot_id: object, rank: object) -> str:
    """Return a stable line, including for future DLC mascots and unknown ranks."""
    rank_key = str(rank).upper()
    if rank_key not in DEFAULT_RANK_LINES:
        rank_key = "D"
    mascot_lines = MASCOT_RANK_LINES.get(str(mascot_id).casefold(), DEFAULT_RANK_LINES)
    return mascot_lines.get(rank_key, DEFAULT_RANK_LINES[rank_key])
